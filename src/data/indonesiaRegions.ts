// Gabungan seluruh Kabupaten / Kota standar
export const MASTER_KABUPATEN_LIST: string[] = Array.from(
  new Set(Object.values(KABUPATEN_BY_PROVINCE).flat())
).sort();

/**
 * Helper untuk mendapatkan daftar opsi Kabupaten / Kota yang relevan
 * @param selectedProvince Nama provinsi terpilih (opsional)
 * @param extraDistricts Kabupaten/Kota tambahan dari database sekolah (opsional)
 */
export function getKabupatenOptions(
  selectedProvince?: string,
  extraDistricts: string[] = []
): string[] {
  let list: string[] = [];

  if (selectedProvince && selectedProvince !== 'ALL' && KABUPATEN_BY_PROVINCE[selectedProvince]) {
    list = [...KABUPATEN_BY_PROVINCE[selectedProvince]];
  } else {
    list = [...MASTER_KABUPATEN_LIST];
  }

  extraDistricts.forEach((dist) => {
    const trimmed = dist?.trim();
    if (trimmed && !list.includes(trimmed)) {
      list.push(trimmed);
    }
  });

  return list.sort();
}

