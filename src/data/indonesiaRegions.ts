// Gabungan seluruh kecamatan standar di Indonesia (deduplicated & sorted)
export const MASTER_KECAMATAN_LIST: string[] = Array.from(
  new Set(Object.values(KECAMATAN_BY_PROVINCE).flat())
).sort();

/**
 * Helper untuk mendapatkan daftar opsi Kecamatan yang relevan
 * @param selectedProvince Nama propinsi terpilih (opsional)
 * @param extraSubdistricts Kecamatan tambahan dari database sekolah (opsional)
 */
export function getKecamatanOptions(
  selectedProvince?: string,
  extraSubdistricts: string[] = []
): string[] {
  let list: string[] = [];

  if (selectedProvince && selectedProvince !== 'ALL' && KECAMATAN_BY_PROVINCE[selectedProvince]) {
    list = [...KECAMATAN_BY_PROVINCE[selectedProvince]];
  } else {
    list = [...MASTER_KECAMATAN_LIST];
  }

  // Tambahkan kecamatan dari data input sekolah jika ada yang belum terdaftar
  extraSubdistricts.forEach((sub) => {
    const trimmed = sub?.trim();
    if (trimmed && !list.includes(trimmed)) {
      list.push(trimmed);
    }
  });

  return list.sort();
}

